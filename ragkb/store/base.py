"""Store interfaces: chunks and vectors (VectorStore) and everything else (MetadataStore)."""
from __future__ import annotations

from typing import Any, Protocol

from ragkb.models import Chunk, Collection, Document, DocumentStatus, Feedback, Hit, Job


class VectorStore(Protocol):
    def upsert(self, chunks: list[Chunk], vectors: list[list[float]]) -> None: ...

    def delete_doc(self, doc_id: str, *, keep_ordinals_below: int | None = None) -> int: ...

    def delete_collection(self, collection_id: str) -> int: ...

    def vector_search(self, collection_id: str, vector: list[float], k: int, min_score: float = 0.0) -> list[Hit]: ...

    def text_search(self, collection_id: str, query: str, k: int) -> list[Hit]: ...

    def chunks_for(self, doc_id: str) -> list[Chunk]: ...

    def neighbours(self, doc_id: str, ordinal: int, span: int = 1) -> list[Chunk]: ...

    def count(self, collection_id: str | None = None) -> int: ...

    def has_documents(self, collection_id: str) -> bool: ...


class MetadataStore(Protocol):
    # collections
    def create_collection(self, name: str, description: str = "") -> Collection: ...
    def get_collection(self, collection_id: str) -> Collection | None: ...
    def list_collections(self) -> list[Collection]: ...
    def delete_collection(self, collection_id: str) -> None: ...

    # documents
    def create_document(self, doc: Document) -> Document: ...
    def get_document(self, doc_id: str) -> Document | None: ...
    def list_documents(self, collection_id: str) -> list[Document]: ...
    def count_documents(self, collection_id: str) -> dict[str, int]: ...   # by status value, e.g. {"ready": 10, "failed": 1}
    def update_document(self, doc_id: str, **fields: Any) -> Document: ...
    def delete_document(self, doc_id: str) -> None: ...
    def find_by_hash(self, collection_id: str, content_hash: str) -> Document | None: ...
    def find_by_path(self, collection_id: str, source_path: str) -> Document | None: ...
    def find_by_title(self, collection_id: str, title: str) -> Document | None: ...

    # jobs
    def create_job(self, collection_id: str, doc_id: str, *, filename: str = "", bytes_total: int | None = None) -> Job: ...
    def get_job(self, job_id: str) -> Job | None: ...
    def list_jobs(self, collection_id: str, limit: int = 50) -> list[Job]: ...
    def update_job(
        self,
        job_id: str,
        status: DocumentStatus | None = None,
        error: str | None = None,
        *,
        doc_id: str | None = None,
        **progress: Any,   # stage, chunks_done, chunks_total, eta_seconds, already_indexed, replaced_doc_id, replaced_title
    ) -> Job: ...
    def request_cancel(self, job_id: str) -> Job | None: ...
    def cancel_requested(self, job_id: str) -> bool: ...

    # answers and feedback
    def save_answer(self, answer_json: str, answer_id: str, collection_id: str) -> None: ...
    def get_answer(self, answer_id: str) -> str | None: ...
    def add_feedback(self, feedback: Feedback) -> None: ...
    def list_feedback(self, collection_id: str | None = None, limit: int = 100) -> list[Feedback]: ...

    # audit and version
    def audit(self, event: str, **fields: Any) -> None: ...
    def bump_version(self) -> str: ...
    def current_version(self) -> str: ...
